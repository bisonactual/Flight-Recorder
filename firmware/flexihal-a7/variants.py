"""Write platformio.local.ini: a flight recorder variant of Expatria's Flexi-HAL A7 builds.

Each variant extends Expatria's environment, so it keeps their board, linker
script (UF2 bootloader at 0x08010000), options and UF2 output, and adds only:
  - the flight recorder plugin (lib flight_recorder) and FLIGHT_RECORDER_ENABLE=1;
  - EEPROM_IS_FRAM=1: settings live in the FM24V10 FRAM fitted at U27.
Builds that enable MPG are left out: MPG stays off with the FRAM.

Usage: variants.py <pio project config --json-output> [--list]
"""

import json
import re
import sys

PREFIX = "env:f446re_flexi_cnc_"

# Which of Expatria's builds get a variant, by name after the prefix. PrintNC only for now;
# every other Flexi-HAL build also works this way (all 17 built on 31 Oct 2026).
FAMILIES = ("printnc",)


def option(options, name):
    for key, value in options:
        if key == name:
            return value if isinstance(value, list) else [value]
    return []


def main():
    config = json.load(open(sys.argv[1]))
    variants, skipped = [], []
    for section, options in config:
        if not section.startswith(PREFIX) or not option(options, "board"):
            continue
        if not section[len(PREFIX):].startswith(FAMILIES):
            continue
        flags = " ".join(option(options, "build_flags"))
        if re.search(r"-D\s*MPG_ENABLE\s*=\s*[1-9]", flags):
            skipped.append((section[4:], "enables MPG"))
            continue
        # Named after the build: Expatria's own labels repeat (two builds say 5AXIS_billmill_nojerk),
        # which would make one UF2 overwrite the other.
        variants.append((section[4:], section[len(PREFIX):].upper()))

    if "--list" in sys.argv:
        for name, version in variants:
            print(f"{name}_fr\t{version}_FR")
        for name, why in skipped:
            print(f"# skipped {name}: {why}")
        return

    print("; Generated by Flight-Recorder firmware/flexihal-a7/build.sh: do not edit.")
    print("; Expatria's Flexi-HAL A7 builds, each with the flight recorder added.\n")
    print("[flight_recorder]")
    print("build_flags =\n  -D FLIGHT_RECORDER_ENABLE=1\n  -D EEPROM_IS_FRAM=1\n")
    for name, version in variants:
        print(f"[env:{name}_fr]")
        print(f"extends = env:{name}")
        print(f"custom_prog_version = {version}_FR")
        print(f"build_flags = ${{env:{name}.build_flags}}\n  ${{flight_recorder.build_flags}}")
        print(f"lib_deps = ${{env:{name}.lib_deps}}\n  flight_recorder\n")
    for name, why in skipped:
        print(f"; skipped {name}: {why}")


if __name__ == "__main__":
    main()
